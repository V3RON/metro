function materialize(base) {
  for (const [kind, p, a, b] of FIXTURE) {
    const full = path.join(base, p);
    if (kind === 'dir') {
      fs.mkdirSync(full, {recursive: true});
    } else if (kind === 'file') {
      fs.writeFileSync(full, 'x'.repeat(a));
      fs.utimesSync(full, BASE_SEC + b, BASE_SEC + b);
    } else if (kind === 'link') {
      fs.symlinkSync(a.replace('$B', base), full);
    } else if (kind === 'chmod') {
      fs.chmodSync(full, a);
    }
  }
}
function cleanup(base) {
  try {
    fs.chmodSync(path.join(base, 'root/unreadable_dir'), 0o755);
  } catch {}
  fs.rmSync(base, {recursive: true, force: true});
}

