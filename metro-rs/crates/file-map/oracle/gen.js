// A seeded PRNG, so that the data is reproducible.
function rng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Random paths for the random trees. Symlinks are named `l1` or `l2` and point
// at plain paths (no link in them): a symlink whose target runs through
// symlinks can make the JS lookup grow its path forever.
function pathMaker(r, names) {
  const plain = (withParent = true) => {
    const depth = 1 + Math.floor(r() * 3);
    const parts = [];
    for (let i = 0; i < depth; i++) {
      parts.push(names[Math.floor(r() * names.length)]);
    }
    if (withParent && r() < 0.1) {
      parts.unshift('..');
    }
    return parts.join('/');
  };
  // May run through a symlink anywhere.
  const mixed = () => {
    const p = plain().split('/');
    if (r() < 0.25) {
      p.splice(Math.floor(r() * (p.length + 1)), 0, r() < 0.5 ? 'l1' : 'l2');
    }
    return p.join('/');
  };
  // The path of a symlink node.
  const linkPath = () => {
    const p = plain(false).split('/');
    p.pop();
    p.push(r() < 0.5 ? 'l1' : 'l2');
    return p.join('/');
  };
  return {plain, mixed, linkPath};
}

