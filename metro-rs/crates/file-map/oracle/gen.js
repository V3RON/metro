async function runCrawls() {
  const cases = [];
  for (const c of CRAWLS) {
    const extensions = c.extensions ?? ['js', 'json'];
    const includeSymlinks = c.includeSymlinks ?? true;
    const retainAllFiles = c.retainAllFiles ?? false;
    const ignoreInput = c.ignore ? new RegExp(c.ignore[0], c.ignore[1]) : null;
    // FileMap's constructor appends VCS_DIRECTORIES.
    const ignorePattern = ignoreInput
      ? new RegExp(ignoreInput.source.concat('|' + VCS_DIRECTORIES), ignoreInput.flags)
      : new RegExp(VCS_DIRECTORIES);
    // FileMap.#buildFileDelta + Watcher.#crawl.
    const ignore = filePath => {
      const ignoreMatched = ignorePattern.test(filePath);
      return (
        (ignoreMatched || (!retainAllFiles && filePath.includes(NODE_MODULES))) ||
        (c.healthCheckFilePrefix != null &&
          path.basename(filePath).startsWith(c.healthCheckFilePrefix))
      );
    };
    const rootDir = unsub(c.rootDir);
    const tfs = new TreeFS({rootDir, processFile() {}});
    tfs.bulkAddOrModify(new Map(PREV_STATES[c.prev ?? 'none']));
    const warnings = [];
    const result = await nodeCrawl({
      console: {warn: m => warnings.push(sub(m))},
      extensions,
      ignore,
      includeSymlinks,
      rootDir,
      roots: c.roots.map(unsub),
      previousState: {fileSystem: tfs, clocks: new Map()},
      subpath: c.subpath,
      computeSha1: false,
      onStatus() {},
    });
    const changed = Array.from(result.changedFiles)
      .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))
      .map(([p, m]) => {
        const meta = m.slice();
        // The size of an absolute symlink is the length of the fixture's path.
        if (p.endsWith('link_abs')) {
          meta[1] = null;
        }
        // The mtime of a symlink is the time the fixture was made.
        if (m[4] === 1 || typeof m[4] === 'string') {
          if (!(m[0] != null && m[2] === 1)) {
            meta[0] = null;
          }
        }
        return [p, meta];
      });
    const removed = Array.from(result.removedFiles).sort();
    warnings.sort();
    cases.push({c, extensions, includeSymlinks, retainAllFiles, changed, removed, warnings});
  }
  emit('pub const CRAWLS: &[CrawlCase] = &[');
  for (const {c, extensions, includeSymlinks, retainAllFiles, changed, removed, warnings} of cases) {
    emit('    CrawlCase {');
    emit(`        name: ${q(c.name)},`);
    emit(`        root_dir: ${q(c.rootDir)},`);
    emit(`        roots: &[${c.roots.map(q).join(', ')}],`);
    emit(`        extensions: &[${extensions.map(q).join(', ')}],`);
    emit(`        include_symlinks: ${includeSymlinks},`);
    emit(`        retain_all_files: ${retainAllFiles},`);
    emit(`        ignore: ${c.ignore ? `Some((${q(c.ignore[0])}, ${q(c.ignore[1])}))` : 'None'},`);
    emit(`        health_check_file_prefix: ${c.healthCheckFilePrefix != null ? `Some(${q(c.healthCheckFilePrefix)})` : 'None'},`);
    emit(`        prev: ${q(c.prev ?? 'none')},`);
    emit(`        subpath: ${c.subpath != null ? `Some(${q(c.subpath)})` : 'None'},`);
    emit(`        changed: &[${changed.map(([p, m]) => `(${q(p)}, ${j(m)})`).join(', ')}],`);
    emit(`        removed: &[${removed.map(q).join(', ')}],`);
    emit(`        warnings: &[${warnings.map(q).join(', ')}],`);
    emit('    },');
  }
  emit('];');
}

