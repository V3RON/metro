function emitAggregator() {
  const r = rng(2);
  const paths = ['a', 'b/c', 'b/d', 'e.js', '../x'];
  const dirs = ['b', 'b/c', 'f', '..'];
  const metas = [mk(1, 1, 1, null, 0), mk(2, 2, 1, 'h', 0), mk(3, 3, 0, null, 'a'), mk(4, 4, 1, null, 1)];
  const pick = a => a[Math.floor(r() * a.length)];
  const scenarios = [];
  for (let n = 0; n < 300; n++) {
    const ops = [];
    const len = 1 + Math.floor(r() * 12);
    for (let i = 0; i < len; i++) {
      const k = r();
      if (k < 0.15) ops.push(['da', pick(dirs)]);
      else if (k < 0.3) ops.push(['dr', pick(dirs)]);
      else if (k < 0.5) ops.push(['fa', pick(paths), pick(metas)]);
      else if (k < 0.75) ops.push(['fm', pick(paths), pick(metas), pick(metas)]);
      else ops.push(['fr', pick(paths), pick(metas)]);
    }
    scenarios.push(ops);
  }
  emit('/// (ops, expected view, expected size). ops: da/dr path, fa path meta, fm path old new, fr path meta');
  emit('pub const AGGREGATOR: &[(&str, &str, usize)] = &[');
  for (const ops of scenarios) {
    const agg = new FileSystemChangeAggregator();
    for (const [op, p, a, b] of ops) {
      if (op === 'da') agg.directoryAdded(p);
      else if (op === 'dr') agg.directoryRemoved(p);
      else if (op === 'fa') agg.fileAdded(p, a);
      else if (op === 'fm') agg.fileModified(p, a, b);
      else agg.fileRemoved(p, a);
    }
    emit(`    (${j(ops)}, ${j(viewOf(agg))}, ${agg.getSize()}),`);
  }
  emit('];');
}

// Random trees with events (watch mode) and deltas (applyFileDelta's tree part).
function emitTreeOps() {
  const r = rng(3);
  const names = ['a', 'b', 'c'];
  const pm = pathMaker(r, names);
  const randomEntry = () => {
    const k = r();
    const symlink = k < 0.75 ? 0 : k < 0.93 ? pm.plain() : 1;
    return [
      symlink === 0 ? pm.plain(false) : pm.linkPath(),
      mk(Math.floor(r() * 4), Math.floor(r() * 4), r() < 0.8 ? 1 : 0, r() < 0.5 ? null : 'h' + Math.floor(r() * 3), symlink),
    ];
  };
  const scenarios = [];
  for (let n = 0; n < 250; n++) {
    const initial = new Map();
    const count = Math.floor(r() * 7);
    for (let i = 0; i < count; i++) {
      initial.set(...randomEntry());
    }
    const events = [];
    const evCount = 1 + Math.floor(r() * 8);
    const existing = () => Array.from(initial.keys())[Math.floor(r() * initial.size)];
    for (let i = 0; i < evCount; i++) {
      if (r() < 0.4) {
        events.push(['delete', r() < 0.5 && initial.size > 0 ? existing() : pm.mixed()]);
      } else {
        const [p, m] = randomEntry();
        events.push(['touch', r() < 0.3 ? pm.mixed() : r() < 0.3 && initial.size > 0 ? existing() : p, m]);
      }
    }
    const removed = [];
    const changed = new Map();
    for (let i = 0; i < Math.floor(r() * 4); i++) {
      removed.push(r() < 0.6 && initial.size > 0 ? existing() : pm.mixed());
    }
    for (let i = 0; i < Math.floor(r() * 5); i++) {
      const [p, m] = randomEntry();
      m[2] = 1;
      changed.set(p, m);
    }
    scenarios.push({initial: entriesOf(initial), events, removed, changed: entriesOf(changed)});
  }

  const run = (tfs, fn) => {
    try {
      fn();
      return null;
    } catch (e) {
      return String(e.message);
    }
  };

  emit('/// (initial, events, expected view, expected listing, expected throw) for watch events');
  emit('pub const EVENTS: &[(&str, &str, &str, &str, &str)] = &[');
  for (const s of scenarios) {
    const tfs = new TreeFS({rootDir: ROOT, processFile() {}});
    if (run(tfs, () => tfs.bulkAddOrModify(new Map(s.initial))) != null) {
      continue;
    }
    const agg = new FileSystemChangeAggregator();
    const err = run(tfs, () => {
      for (const [type, p, meta] of s.events) {
        if (type === 'delete') tfs.remove(p, agg);
        else tfs.addOrModify(p, meta, agg);
      }
    });
    emit(`    (${j(s.initial)}, ${j(s.events)}, ${j(viewOf(agg))}, ${j(listing(tfs))}, ${q(err ?? '')}),`);
  }
  emit('];');

  emit('/// (initial, removed, changed, expected view, expected listing, expected throw) for applyFileDelta');
  emit('pub const DELTAS: &[(&str, &str, &str, &str, &str, &str)] = &[');
  for (const s of scenarios) {
    const tfs = new TreeFS({rootDir: ROOT, processFile() {}});
    if (run(tfs, () => tfs.bulkAddOrModify(new Map(s.initial))) != null) {
      continue;
    }
    const agg = new FileSystemChangeAggregator();
    const err = run(tfs, () => {
      for (const p of s.removed) tfs.remove(p, agg);
      tfs.bulkAddOrModify(new Map(s.changed), agg);
    });
    emit(`    (${j(s.initial)}, ${j(s.removed)}, ${j(s.changed)}, ${j(viewOf(agg))}, ${j(listing(tfs))}, ${q(err ?? '')}),`);
  }
  emit('];');
}

