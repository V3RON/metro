function emitSha1() {
  emit('/// (content, sha1 hex)');
  emit('pub const SHA1S: &[(&str, &str)] = &[');
  for (const c of ['', 'x', 'hello\n', 'x'.repeat(10), '\u00e9\u00fc']) {
    emit(`    (${q(c)}, ${q(createHash('sha1').update(c).digest('hex'))}),`);
  }
  emit('];');
}

