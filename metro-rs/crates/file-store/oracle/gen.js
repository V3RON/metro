// Regenerates src/oracle_data.rs from the JS TreeFS (the source of truth).
// Usage, from the repo root:  node metro-rs/crates/file-store/oracle/gen.js > metro-rs/crates/file-store/src/oracle_data.rs && (cd metro-rs && cargo fmt)
const REPO = require('path').resolve(__dirname, '../../../..');
require(REPO + '/packages/metro-babel-register').unstable_registerForMetroMonorepo();
const TreeFS = require(REPO + '/packages/metro-file-map/src/lib/TreeFS').default;
const root = '/proj/root';
const files = ['a/b/c.js','a/package.json','node_modules/pkg/package.json','node_modules/pkg/index.js','node_modules/pkg/lib/x.js','z.js','../other/app/index.js','../other/package.json','../../top.js','../root2/q.js','éü/ö.js','package.json'];
const links = {link:'a', cyc1:'cyc2', cyc2:'cyc1', up:'..', rootlink:'', far:'../other/app', dead:'nope', filelink:'z.js', '../other/back':'../root', 'a/self':'a', 'ééé': '../other'};
const mk = t => { const m = new Array(8).fill(0); m[4]=t; return m; };
const tfs = new TreeFS({rootDir: root, processFile(){}});
const map = new Map();
for (const f of files) map.set(f, mk(0));
for (const [k,v] of Object.entries(links)) map.set(k, mk(v));
tfs.bulkAddOrModify(map);
const queries = ['','a','a/','a/b/c.js','/proj/root/a/b/c.js','/proj/root/a/b/','link','link/','link/b/c.js','link/b/nope.js','cyc1','cyc1/x','up','up/root/z.js','up/other/app/index.js','rootlink','rootlink/z.js','rootlink/a/b','far','far/index.js','far/nope','dead','dead/x','filelink','filelink/x','z.js/','..','../..','../../..','../other','../other/app/index.js','/proj','/','/proj/other/app/index.js','/top.js','/proj/../proj/root/z.js','./z.js','a/./b','a/../z.js','../root/z.js','../root','/proj/root/../root2/q.js','/nonexistent/x','../zzz','../zzz/y','../../zzz/y','éü/ö.js','éü','ééé/app/index.js','a/self/b/c.js','../other/back/z.js','/proj/root','/proj/root/','/proj/root//a'];
const hq = ['a/b/c.js','a/b/nope/deep.js','a','a/','link/b/c.js','node_modules/pkg/lib/x.js','node_modules/pkg/lib/nope.js','node_modules/nopkg/x.js','node_modules','z.js','éü/ö.js','nothere/x.js','../other/app/index.js','../other/app/zz/deep.js','../root2/q.js','../zzz/y.js','../../top.js','..','../..','../../..','/proj/root/a/b/c.js','/proj/other/x','/x/y/z','/','up/root/a/b/c.js','up/other/app/index.js','rootlink/a/b/c.js','far/index.js','far/nope.js','../other/back/a/b/c.js','ééé/app/index.js','ééé/app/ü.js','cyc1/x','dead/x','z.js/q','a/b/c.js/d'];
const q = s => JSON.stringify(s);
const lines = [];
lines.push('// @generated by oracle/gen.js from the JS TreeFS. Do not edit by hand.');
lines.push(`pub const ROOT: &str = ${q(root)};`);
lines.push('pub const FILES: &[&str] = &[' + files.map(q).join(', ') + '];');
lines.push('pub const LINKS: &[(&str, &str)] = &[' + Object.entries(links).map(([k,v]) => `(${q(k)}, ${q(v)})`).join(', ') + '];');
lines.push('/// (query, "N" | "F:<real>" | "D:<real>")');
lines.push('pub const LOOKUPS: &[(&str, &str)] = &[');
for (const x of queries) { const r = tfs.lookup(x); lines.push(`    (${q(x)}, ${q(r.exists ? (r.type==='d'?'D:':'F:')+r.realPath : 'N')}),`); }
lines.push('];');
lines.push('pub const EXISTS: &[(&str, bool)] = &[');
for (const x of queries) lines.push(`    (${q(x)}, ${tfs.exists(x)}),`);
lines.push('];');
lines.push('/// (start, subpath, is_dir, break_on, Some((absolute, container_relative)) | None | THROW)');
lines.push('pub enum Hier { None, Some(&\'static str, &\'static str), Throw }');
lines.push('pub const HIER: &[(&str, &str, bool, Option<&str>, Hier)] = &[');
for (const x of hq) for (const [sub, ty, br] of [['package.json','f','node_modules'],['package.json','f',null],['node_modules/pkg','d',null]]) {
  let r; try { r = tfs.hierarchicalLookup(x, sub, {breakOnSegment: br, subpathType: ty}); } catch (e) { r = 'THROW'; }
  const h = r === 'THROW' ? 'Hier::Throw' : r ? `Hier::Some(${q(r.absolutePath)}, ${q(r.containerRelativePath)})` : 'Hier::None';
  lines.push(`    (${q(x)}, ${q(sub)}, ${ty==='d'}, ${br ? 'Some('+q(br)+')' : 'None'}, ${h}),`);
}
lines.push('];');

// Mutation scenarios: a fresh tree per scenario, one op sequence, then the listing.
const listing = t => Array.from(t.metadataIterator({includeNodeModules: true, includeSymlinks: true}), ({canonicalPath, metadata}) => canonicalPath + (metadata[4] === 0 ? '|f' : '|l:' + metadata[4])).sort();
const fresh = () => { const t = new TreeFS({rootDir: root, processFile(){}}); t.bulkAddOrModify(new Map(map)); return t; };
const ops = [
  ['remove', 'a/b/c.js'], ['remove', 'node_modules'], ['remove', '../other/app/index.js'], ['remove', '../../top.js'],
  ['remove', '/proj/root/a'], ['remove', 'link'], ['remove', 'link/b'], ['remove', 'éü'], ['remove', 'nonexistent/x'], ['remove', '../root2/q.js'],
  ['remove', ''], ['remove', '..'], ['remove', '../other'], ['remove', 'a/'],
  ['add', 'link/new.js'], ['add', '/proj/root/q/r/s.js'], ['add', 'up/root/zz.js'], ['add', 'a'], ['add', 'z.js/under'],
  ['add', 'far/new.js'], ['add', 'cyc1/x'], ['add', 'top2.js'], ['add', '../../../deep/er.js'], ['addlink', 'newlink', 'a/b'], ['add', 'newlink/c2.js'],
];
lines.push('/// (op, path, target, listing after) on a fresh tree each');
lines.push('pub const MUTATIONS: &[(&str, &str, &str, &[&str])] = &[');
for (const [op, p, target] of ops) {
  const t = fresh();
  let res = '';
  try {
    if (op === 'remove') t.remove(p);
    else if (op === 'add') t.addOrModify(p, mk(0));
    else t.addOrModify(p, mk(target));
  } catch (e) { res = 'THROW'; }
  const l = res ? [res] : listing(t);
  lines.push(`    (${q(op)}, ${q(p)}, ${q(target || '')}, &[${l.map(q).join(', ')}]),`);
}
lines.push('];');

// RootPathUtils
const {RootPathUtils} = require(REPO + '/packages/metro-file-map/src/lib/RootPathUtils');
lines.push('/// (rootDir, function, arg1, arg2, result); join results are "normalPath|collapsedSegments"');
lines.push('pub const RPU: &[(&str, &str, &str, &str, &str)] = &[');
const attempt = f => { try { return f(); } catch (e) { return 'THROW'; } };
for (const rd of ['/proj/root', '/']) {
  const u = new RootPathUtils(rd);
  for (const a of ['/proj/root','/proj/root/','/proj/root/a/b','/proj/root/a/','/proj','/proj/','/','/proj/other/x','/proj/root/../root/x','/proj/root/./a','/proj/root/a/../b','/proj/../proj/root/q','/proj2/x','/proj/rootx/a','/a/b/c','/proj/root/../../x','/proj/root/../..','/proj/root/../../','/proj/root/a/..','//proj/root/a','/proj/root/a//b']) lines.push(`    (${q(rd)}, "absoluteToNormal", ${q(a)}, "", ${q(u.absoluteToNormal(a))}),`);
  for (const n of ['','..','../..','../../..','../a','../../a/b','a/b','../','a/']) lines.push(`    (${q(rd)}, "normalToAbsolute", ${q(n)}, "", ${q(u.normalToAbsolute(n))}),`);
  for (const r of ['a','./a','a/./b','../root/a','../x','..','../..','../../../..','','.','a/../b','../root','../root/','a/']) lines.push(`    (${q(rd)}, "relativeToNormal", ${q(r)}, "", ${q(u.relativeToNormal(r))}),`);
  for (const [n,r] of [['',''],['','a'],['a','b'],['a/','b'],['..','root/a'],['../..','proj/root/a'],['..','x'],['../..','x/y'],['..','root'],['../..','proj'],['a/..','x']]) lines.push(`    (${q(rd)}, "joinNormalToRelative", ${q(n)}, ${q(r)}, ${q(attempt(() => { const v = u.joinNormalToRelative(n,r); return v.normalPath + '|' + v.collapsedSegments; }))}),`);
  for (const [sl,l] of [['a/b','c'],['a/b','../c'],['a/b','/proj/root/x'],['a/b','../../..'],['a','/'],['a/b','./x/../y'],['a/b','']]) lines.push(`    (${q(rd)}, "resolveSymlinkToNormal", ${q(sl)}, ${q(l)}, ${q(u.resolveSymlinkToNormal(sl,l))}),`);
}
lines.push('];');

// Randomised differential corpus (seeded, deterministic): small trees with
// symlinks (including ones pointing above the root), queried with lookup and
// hierarchicalLookup. Each case: (entries, queries, expected lines).
let seed = 12345;
const rnd = n => { seed = (seed * 1103515245 + 12345) & 0x7fffffff; return seed % n; };
const segs = ['a', 'b', 'c', 'node_modules', 'p', 'é'];
const pick = a => a[rnd(a.length)];
const randPath = (allowUp) => { const n = 1 + rnd(4); const parts = []; if (allowUp) { const u = rnd(4); for (let i = 0; i < u; i++) parts.push('..'); } for (let i = 0; i < n; i++) parts.push(pick(segs)); return parts.join('/'); };
lines.push('/// Random cases: (entries "path|f" or "path|l:target", queries, expected). expected has one line per query:');
lines.push('/// "<lookup>;<exists>;<hier package.json break node_modules>;<hier node_modules/p dir, no break>"');
lines.push('pub const RANDOM: &[(&[&str], &[&str], &[&str])] = &[');
for (let c = 0; c < 40; c++) {
  const t = new TreeFS({rootDir: '/w/x/root', processFile(){}});
  const m = new Map(); const entries = [];
  const n = 4 + rnd(12);
  for (let i = 0; i < n; i++) {
    const kind = rnd(4);
    let pth = randPath(rnd(5) === 0);
    if (rnd(3) === 0) pth = pth.replace(/[^/]+$/, 'package.json');
    if (kind === 0) { const tg = rnd(6) === 0 ? '' : randPath(rnd(2) === 0); m.set(pth, mk(tg)); entries.push(pth + '|l:' + tg); }
    else { m.set(pth, mk(0)); entries.push(pth + '|f'); }
  }
  try { t.bulkAddOrModify(m); } catch (e) { continue; }
  const qs = [];
  for (let i = 0; i < 40; i++) { let qq = randPath(rnd(4) === 0); if (rnd(5) === 0) qq = '/w/x/root/' + qq; if (rnd(8) === 0) qq += '/'; qs.push(qq); }
  const res = qs.map(qq => {
    let a; try { const r = t.lookup(qq); a = r.exists ? (r.type==='d'?'D:':'F:')+r.realPath : 'N'; } catch (e) { a = 'THROW'; }
    const h = (sub, ty, br) => { try { const r = t.hierarchicalLookup(qq, sub, {breakOnSegment: br, subpathType: ty}); return r ? r.absolutePath + '>' + r.containerRelativePath : 'null'; } catch (e) { return 'THROW'; } };
    return [a, String(t.exists(qq)), h('package.json','f','node_modules'), h('node_modules/p','d',null)].join(';');
  });
  lines.push(`    (&[${entries.map(q).join(', ')}], &[${qs.map(q).join(', ')}], &[${res.map(q).join(', ')}]),`);
}
lines.push('];');
console.log(lines.join('\n'));
