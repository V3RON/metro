/**
 * Writes port/reports/phase-<n>.md (and .json) from the outputs of a full
 * `./gate.sh --report` run in port/.gate/. Called by gate.sh.
 */
'use strict';

const {execFileSync} = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const PORT = path.resolve(__dirname, '..');
const GATE = path.join(PORT, '.gate');
const n = process.argv[2];
const read = f => fs.readFileSync(path.join(GATE, f), 'utf8');
const result = JSON.parse(read('result.json'));
const perf = JSON.parse(read('perf/perf.json'));
const diff = JSON.parse(read('diff/diff.json'));
const phase = JSON.parse(execFileSync('node', [path.join(__dirname, 'phase.js'), 'json', n]).toString());

if (!result.passed || !perf.passed || !diff.passed || perf.quick) {
  console.error('report.js: the last gate run did not pass in full; no report written.');
  process.exit(1);
}

// "Tests: 3 skipped, 2900 passed, 2903 total" lines from each Jest run.
const testsLog = read('tests.log');
const jestRuns = [...testsLog.matchAll(/### tests: (jest[^\n]*)[\s\S]*?^Tests:\s+([^\n]+)/gm)].map(m => `- ${m[1]}: ${m[2]}`);
const cargo = [...testsLog.matchAll(/^test result: ok\. (\d+) passed/gm)].reduce((s, m) => s + Number(m[1]), 0);
const skipped = execFileSync('node', [path.join(__dirname, 'phase.js'), 'js-only', perf.candidate.metroRust]).toString().trim().split('\n').filter(Boolean);

const md = [
  `# Phase ${n} report: ${phase.title}`,
  '',
  `Generated by \`./gate.sh --report\` on ${perf.date.slice(0, 10)} at commit \`${perf.candidate.commit.slice(0, 12)}\`${perf.candidate.dirty ? ' (with uncommitted changes, so this report is not valid for approval)' : ''}.`,
  `Components in Rust: \`${perf.candidate.metroRust}\`. The full gate took ${Math.round(result.seconds / 60)} minutes.`,
  '',
  '## Decision needed',
  '',
  `All gates passed. Phase ${Number(n) + 1} starts only after Szymon approves this one by adding \`port/approvals/phase-${n}.md\` (see RULES.md).`,
  '',
  '## Exit criteria for this phase',
  '',
  phase.exit,
  '',
  '## Compile',
  '',
  'cargo fmt, cargo clippy with warnings as errors, the native binding build, flow and eslint all passed.',
  '',
  '## Tests',
  '',
  cargo ? `- cargo test: ${cargo} passed` : '- cargo test: no Rust tests',
  ...jestRuns,
  `- Differential bundles: ${diff.results.map(r => `${r.file} identical`).join(', ')}`,
  skipped.length ? `- Skipped in Rust mode because they only test the JS implementation (${skipped.length}): ${skipped.map(s => `\`${s}\``).join(', ')}` : '- No JS-only tests skipped in Rust mode.',
  '',
  '## Performance',
  '',
  read('perf/perf.md').split('\n').slice(1).join('\n').trim(),
  '',
].join('\n');

fs.mkdirSync(path.join(PORT, 'reports'), {recursive: true});
fs.writeFileSync(path.join(PORT, 'reports', `phase-${n}.md`), md);
fs.writeFileSync(path.join(PORT, 'reports', `phase-${n}.json`), JSON.stringify({result, perf, diff}, null, 2) + '\n');
